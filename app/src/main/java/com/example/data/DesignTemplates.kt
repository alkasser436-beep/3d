  fun createFurnitureItem(kind: FurnitureKind, existingCount: Int): FurnitureItem {
    val offset = ((existingCount % 5) - 2) * 0.28f
    return FurnitureItem(
      id = "item_${UUID.randomUUID().toString().take(8)}",
      kind = kind,
      label = kind.displayName,
      widthMeters = kind.defaultW,
      depthMeters = kind.defaultD,
      heightMeters = kind.defaultH,
      xMeters = offset,
      zMeters = if (kind == FurnitureKind.UPPER_CABINET) -1.2f else offset * 0.5f,
      yMeters = kind.defaultY,
      rotationDeg = 0f,
      material = kind.defaultMaterial,
      secondaryMaterial = kind.defaultSecondaryMaterial,
      style = kind.defaultStyle,
    )
  }
